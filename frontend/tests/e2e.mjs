async function until(predicate, message, timeout = 12000) {
  const deadline = Date.now() + timeout
  while (Date.now() < deadline) { if (await predicate()) return; await pause(100) }
  throw new Error(`Timed out: ${message}\n${serverOutput}`)
}
async function start() {
  server = spawn(java, [...javaArgs, '--no-browser', '--data-dir', dataDir, '--server-info', infoFile], { cwd: root, env: environment, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  server.stdout.on('data', text => { serverOutput += text }); server.stderr.on('data', text => { serverOutput += text })
  await until(async () => { try { info = JSON.parse(await fs.readFile(infoFile, 'utf8')); return true } catch { return false } }, 'server metadata')
  await until(async () => { try { return (await fetch(info.origin)).ok } catch { return false } }, 'server ready')
}
async function api(route, body, headers = {}) {
  const response = await fetch(`${info.origin}/api/${route}`, { method: body === undefined ? 'GET' : 'POST', headers: { Authorization: `Bearer ${info.token}`, 'Content-Type': 'application/json', ...headers }, body: body === undefined ? undefined : JSON.stringify(body) })
  return { status: response.status, data: await response.json() }
}
